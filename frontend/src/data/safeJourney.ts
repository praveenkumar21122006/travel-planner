function haversineKm(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 6371;
  const toR = (d: number) => (d * Math.PI) / 180;
  const dLat = toR(lat2 - lat1);
  const dLng = toR(lng2 - lng1);
  const a =
    Math.sin(dLat / 2) ** 2 + Math.cos(toR(lat1)) * Math.cos(toR(lat2)) * Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

function durationLabel(km: number): string {
  const hours = km / 45;
  const h = Math.floor(hours);
  const m = Math.round((hours - h) * 60);
  return `${h}h ${String(m).padStart(2, "0")}m by Car`;
}

export function nearestOrigin(lat: number, lng: number): { name: string; distanceKm: number } {
  let best: { name: string; distanceKm: number } | null = null;
  for (const [name, c] of Object.entries(ORIGIN_COORDS)) {
    const d = haversineKm(lat, lng, c.lat, c.lng);
    if (!best || d < best.distanceKm) best = { name, distanceKm: d };
  }
  return best ?? { name: "Chennai", distanceKm: 0 };
}

export function resolveTrip(from: string, to: string): PlannedTrip | null {
  const query = to.trim().toLowerCase();
  const profile = DESTINATIONS.find((d) => d.name.toLowerCase() === query);
  if (!profile) return null;

  const fromName = from.trim();

  const curated = profile.origins.find(
    (o) => o.origin.toLowerCase() === fromName.toLowerCase()
  );
  let route: OriginRoute;
  if (curated) {
    route = curated;
  } else {
    const known = ORIGIN_COORDS[fromName];
    if (known) {
      const dist = Math.round(haversineKm(known.lat, known.lng, profile.lat, profile.lng));
      route = {
        origin: fromName,
        lat: known.lat,
        lng: known.lng,
        distanceKm: dist,
        byCar: durationLabel(dist),
      };
    } else {
      route =
        profile.origins.find((o) => o.origin === profile.defaultOrigin) ??
        profile.origins[0];
    }
  }

  return {
    origin: fromName || route.origin,
    destination: profile.name,
    profile,
    route,
    safetyStatus: profile.safetyStatus,
  };
}

