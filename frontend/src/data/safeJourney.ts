export function primaryTravelTime(route: OriginRoute): string {
  if (route.byCar && route.byCar !== "—") return route.byCar;
  return route.flight ?? route.train ?? "—";
}

export function secondaryTravelTime(route: OriginRoute): string | undefined {
  const primary = primaryTravelTime(route);
  if (route.byCar && route.byCar !== "—" && route.byCar !== primary) {
    return `or ${primary}`;
  }
  if (route.flight && route.flight !== primary) return `or ${route.flight}`;
  if (route.train && route.train !== primary) return `or ${route.train}`;
  return undefined;
}